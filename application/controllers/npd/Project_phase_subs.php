            $post = $this->input->post();
            $send = $this->crud->update('project_phase_subs', ["id" => $id], $post);
            echo $send;
        } else {
            show_error("Cannot Process your request");
        }
    }
    //DELETE DATA
    public function delete()
    {
        $data = $this->input->post();
        $send = $this->crud->delete('project_phase_subs', $data);
        echo $send;
    }
